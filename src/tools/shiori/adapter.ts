/**
 * Shiori (枝織) — code to specification writer.
 * Turns the static source model into a contract-style specification in Markdown and
 * a standalone HTML document. Pure function, no network, fully deterministic.
 */

import type { EngineAdapter, EngineRequest, EngineResult, ProviderMode } from '../../adapters/types';
import { baseName, escapeHtml, sha256Hex } from '../../lib/util';
import {
  languageLabel,
  parseSource,
  paramLabel,
  signatureOf,
  type FunctionInfo,
  type ParsedModule,
} from '../../lib/source';

export type SpecSection = 'overview' | 'contracts' | 'behaviour' | 'errors' | 'dependencies' | 'types';

export const ALL_SECTIONS: SpecSection[] = ['overview', 'contracts', 'behaviour', 'errors', 'dependencies', 'types'];

export interface ShioriOptions {
  sections: SpecSection[];
  includePrivate: boolean;
}

export interface ContractRow {
  name: string;
  signature: string;
  params: string;
  returns: string;
  visibility: string;
  async: boolean;
  line: number;
  errors: string[];
}

export interface BehaviourRule {
  function: string;
  line: number;
  condition: string;
  action: string;
  detail?: string;
}

export interface DependencyRow {
  module: string;
  kind: string;
  external: boolean;
  names: string;
  line: number;
}

export interface SpecModel {
  title: string;
  language: string;
  fileName: string;
  functionCount: number;
  typeCount: number;
  guardCount: number;
  errorCount: number;
  contracts: ContractRow[];
  rules: BehaviourRule[];
  dependencies: DependencyRow[];
  errors: { function: string; line: number; error: string; message?: string }[];
  types: { name: string; kind: string; members: string[]; extends?: string; implements?: string[] }[];
  internals: string[];
  notes: string[];
}

export interface ShioriOutput {
  model: SpecModel;
  markdown: string;
  html: string;
}

export function buildSpecModel(fileName: string, source: string): SpecModel {
  const mod: ParsedModule = parseSource(fileName, source);
  const contracts: ContractRow[] = mod.functions.map((fn: FunctionInfo) => ({
    name: fn.isMethod && fn.className ? `${fn.className}.${fn.name}` : fn.name,
    signature: signatureOf(fn),
    params: fn.params.length ? fn.params.map(paramLabel).join(', ') : '—',
    returns: fn.returnType ?? 'void / untyped',
    visibility: fn.isMethod ? (fn.exported ? 'public method' : 'internal method') : fn.exported ? 'exported' : 'module-internal',
    async: fn.async,
    line: fn.startLine,
    errors: [...new Set(fn.errors.map((e) => e.error))],
  }));

  const rules: BehaviourRule[] = [];
  for (const fn of mod.functions) {
    for (const g of fn.guards) {
      rules.push({
        function: fn.name,
        line: g.line,
        condition: g.condition,
        action: g.action,
        detail: g.detail,
      });
    }
  }

  const dependencies: DependencyRow[] = mod.imports.map((imp) => ({
    module: imp.module,
    kind: imp.kind,
    external: imp.external,
    names: imp.names.length ? imp.names.join(', ') : '—',
    line: imp.line,
  }));

  const errors = mod.functions.flatMap((fn) =>
    fn.errors.map((e) => ({ function: fn.name, line: e.line, error: e.error, message: e.message })),
  );

  const types = mod.types.map((t) => ({
    name: t.name,
    kind: t.kind,
    extends: t.extends,
    implements: t.implements,
    members: t.members.length
      ? t.members.map((m) => `${m.name}${m.type ? `: ${m.type}` : ''}`)
      : t.aliasBody
        ? [`alias = ${t.aliasBody}`]
        : [],
  }));

  const internals = mod.functions
    .filter((fn) => !fn.exported && !fn.isMethod)
    .map((fn) => fn.name);

  return {
    title: baseName(fileName),
    language: languageLabel(mod.language),
    fileName,
    functionCount: mod.functions.length,
    typeCount: mod.types.length,
    guardCount: rules.length,
    errorCount: errors.length,
    contracts,
    rules,
    dependencies,
    errors,
    types,
    internals,
    notes: mod.notes,
  };
}

function table(headers: string[], rows: string[][]): string[] {
  const esc = (v: string) => v.replace(/\|/g, '\\|').replace(/\n/g, ' ');
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.map((cell) => esc(cell)).join(' | ')} |`),
  ];
}

export function specToMarkdown(model: SpecModel, sections: SpecSection[] = ALL_SECTIONS): string {
  const out: string[] = [];
  out.push(`# Specification — ${model.title}`, '');
  out.push(
    `*Generated by HD2Lab Aomatsukan · Shiori — deterministic static analysis of ${model.language} source.*`,
    '',
  );

  if (sections.includes('overview')) {
    out.push('## 1. Overview', '');
    out.push(`- **Source file**: \`${model.fileName}\``);
    out.push(`- **Language**: ${model.language}`);
    out.push(`- **Public contracts**: ${model.contracts.filter((c) => c.visibility !== 'module-internal').length}`);
    out.push(`- **Behavioural rules**: ${model.guardCount}`);
    out.push(`- **Error paths**: ${model.errorCount}`);
    out.push(`- **Declared types**: ${model.typeCount}`);
    out.push(`- **External dependencies**: ${model.dependencies.filter((d) => d.external).length}`, '');
    if (model.notes.length) {
      for (const note of model.notes) out.push(`> ${note}`);
      out.push('');
    }
  }

  if (sections.includes('contracts') && model.contracts.length) {
    out.push('## 2. Contract table', '');
    out.push(
      ...table(
        ['#', 'Contract', 'Parameters', 'Returns', 'Visibility', 'Errors'],
        model.contracts.map((c, i) => [
          String(i + 1),
          `\`${c.name}(${c.params})\``,
          c.params,
          c.returns,
          c.visibility,
          c.errors.length ? c.errors.join(', ') : '—',
        ]),
      ),
      '',
    );
    for (const c of model.contracts) {
      out.push(`### \`${c.signature}\``, '');
      out.push(`- **Line**: ${c.line}`);
      out.push(`- **Async**: ${c.async ? 'yes' : 'no'}`);
      if (c.params !== '—') out.push(`- **Accepts**: ${c.params}`);
      out.push(`- **Returns**: ${c.returns}`);
      if (c.errors.length) out.push(`- **May raise**: ${c.errors.join(', ')}`);
      out.push('');
    }
  }

  if (sections.includes('behaviour') && model.rules.length) {
    out.push('## 3. Behaviour rules', '');
    out.push('Guards are the branch points that decide whether a call continues, exits early, or fails.', '');
    out.push(
      ...table(
        ['Function', 'Line', 'When', 'Then'],
        model.rules.map((r) => [
          r.function,
          String(r.line),
          `\`${r.condition}\``,
          `${r.action.toUpperCase()}${r.detail ? ` — \`${r.detail}\`` : ''}`,
        ]),
      ),
      '',
    );
  }

  if (sections.includes('errors') && model.errors.length) {
    out.push('## 4. Error paths', '');
    out.push(
      ...table(
        ['Function', 'Line', 'Error', 'Message'],
        model.errors.map((e) => [e.function, String(e.line), `\`${e.error}\``, e.message ?? '—']),
      ),
      '',
    );
  }

  if (sections.includes('dependencies') && model.dependencies.length) {
    out.push('## 5. Dependencies', '');
    const external = model.dependencies.filter((d) => d.external);
    const local = model.dependencies.filter((d) => !d.external);
    out.push('### External', '');
    out.push(
      external.length
        ? table(['Module', 'Imported names', 'Style'], external.map((d) => [`\`${d.module}\``, d.names, d.kind]))
          .join('\n')
        : 'No external modules are imported.',
      '',
    );
    out.push('### Local', '');
    out.push(
      local.length
        ? table(['Module', 'Imported names', 'Style'], local.map((d) => [`\`${d.module}\``, d.names, d.kind])).join('\n')
        : 'No local modules are imported.',
      '',
    );
  }

  if (sections.includes('types') && model.types.length) {
    out.push('## 6. Data types', '');
    for (const t of model.types) {
      out.push(`### ${t.kind} \`${t.name}\``, '');
      if (t.extends) out.push(`- **Extends**: ${t.extends}`);
      if (t.implements?.length) out.push(`- **Implements**: ${t.implements.join(', ')}`);
      if (t.members.length) {
        out.push('');
        for (const member of t.members) out.push(`- \`${member}\``);
      }
      out.push('');
    }
  }

  out.push('---', '', '*HD2Lab Aomatsukan — Shiori, deterministic specification writer*');
  return `${out.join('\n')}\n`;
}

export function specToHtml(model: SpecModel, sections: SpecSection[] = ALL_SECTIONS): string {
  const md = specToMarkdown(model, sections);
  const lines = md.split('\n');
  const out: string[] = [];

  const renderRows = (rows: string[][]): string => {
    const head = rows[0] ?? [];
    const body = rows.slice(2);
    const thead = `<thead><tr>${head.map((cell) => `<th>${inline(cell)}</th>`).join('')}</tr></thead>`;
    const tbody = `<tbody>${body
      .map((row) => `<tr>${row.map((cell) => `<td>${inline(cell)}</td>`).join('')}</tr>`)
      .join('')}</tbody>`;
    return `<div class="table-wrap"><table>${thead}${tbody}</table></div>`;
  };

  for (let i = 0; i < lines.length; i += 1) {
    const line = lines[i];
    if (/^\|/.test(line)) {
      const rows: string[][] = [];
      while (i < lines.length && /^\|/.test(lines[i])) {
        rows.push(
          lines[i]
            .trim()
            .replace(/^\|/, '')
            .replace(/\|$/, '')
            .split(/(?<!\\)\|/)
            .map((cell) => cell.trim().replace(/\\\|/g, '|')),
        );
        i += 1;
      }
      i -= 1;
      if (rows.length >= 2) out.push(renderRows(rows));
      continue;
    }
    if (/^# /.test(line)) out.push(`<h1>${inline(line.slice(2))}</h1>`);
    else if (/^## /.test(line)) out.push(`<h2>${inline(line.slice(3))}</h2>`);
    else if (/^### /.test(line)) out.push(`<h3>${inline(line.slice(4))}</h3>`);
    else if (/^---$/.test(line)) out.push('<hr />');
    else if (/^> /.test(line)) out.push(`<blockquote>${inline(line.slice(2))}</blockquote>`);
    else if (/^- /.test(line)) out.push(`<li>${inline(line.slice(2))}</li>`);
    else if (!line.trim()) out.push('');
    else out.push(`<p>${inline(line)}</p>`);
  }

  const body = out
    .join('\n')
    .replace(/(<li>[\s\S]*?<\/li>\n?)+/g, (match) => `<ul>\n${match}</ul>\n`);

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>Specification — ${escapeHtml(model.title)}</title>
<style>
  :root { color-scheme: light; }
  body { margin: 0; padding: 48px 24px; background: #edf4ef; color: #16241b;
    font-family: "Inter", "Segoe UI", system-ui, sans-serif; line-height: 1.65; }
  main { max-width: 900px; margin: 0 auto; background: #fff; border: 1px solid #d6e4da;
    border-radius: 16px; padding: 40px 44px; box-shadow: 0 18px 50px rgba(11, 20, 15, 0.08); }
  h1 { font-size: 30px; margin: 0 0 4px; color: #16241b; }
  h2 { font-size: 20px; margin: 32px 0 8px; color: #2d6a4f; border-bottom: 1px solid #dbe8e0; padding-bottom: 6px; }
  h3 { font-size: 16px; margin: 22px 0 6px; color: #1d3b2c; }
  p, li, td, th { font-size: 14px; }
  code { background: #eef6f0; border: 1px solid #dbe8e0; border-radius: 5px; padding: 1px 5px;
    font-family: "JetBrains Mono", ui-monospace, monospace; font-size: 12.5px; }
  blockquote { margin: 12px 0; padding: 10px 14px; border-left: 3px solid #52b788; background: #f4faf6; }
  hr { border: 0; border-top: 1px solid #dbe8e0; margin: 28px 0; }
  .table-wrap { overflow-x: auto; margin: 8px 0 18px; }
  table { width: 100%; border-collapse: collapse; }
  th { text-align: left; font-size: 11px; letter-spacing: 0.09em; text-transform: uppercase;
    color: #5b7066; border-bottom: 2px solid #dbe8e0; padding: 8px 10px; background: #f4faf6; }
  td { border-bottom: 1px solid #eaf1ec; padding: 8px 10px; vertical-align: top; }
  a { color: #2d6a4f; }
</style>
</head>
<body>
<main>
${body}
</main>
</body>
</html>
`;
}

function inline(text: string): string {
  return escapeHtml(text)
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/\*([^*]+)\*/g, '<em>$1</em>');
}

export class ShioriAdapter implements EngineAdapter<ShioriOutput, ShioriOptions> {
  readonly id = 'shiori' as const;
  readonly title = 'Specification Writer';
  readonly japaneseTitle = '枝織';
  readonly providerMode: ProviderMode = 'local-static';
  readonly capabilities = [
    'TypeScript・JavaScript・Python・Java・Go の静的解析',
    '引数・既定値・戻り値まで含むコントラクト表',
    'ガード・早期リターン・エラー経路の振る舞いルール',
    'Markdown とスタンドアロン HTML での書き出し',
  ] as const;

  async run(request: EngineRequest<ShioriOptions>): Promise<EngineResult<ShioriOutput>> {
    const started = performance.now();
    const sections = request.options?.sections?.length ? request.options.sections : ALL_SECTIONS;
    const model = buildSpecModel(request.sourceName, request.source);
    const markdown = specToMarkdown(model, sections);
    const html = specToHtml(model, sections);
    const cacheKey = await sha256Hex(`${this.id}|${request.mode}|${request.source}|${sections.join(',')}`);
    return {
      output: { model, markdown, html },
      providerMode: this.providerMode,
      diagnostics: model.notes.map((note) => ({ severity: 'info' as const, message: note })),
      elapsedMs: Math.round(performance.now() - started),
      cacheKey,
    };
  }
}
